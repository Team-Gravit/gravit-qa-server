-- V1__init_qa_schema.sql

-- 스프린트: Notion 스프린트 DB 행 1개와 1:1
CREATE TABLE sprint
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_key     VARCHAR(100) NOT NULL,
    notion_page_id VARCHAR(64)  NOT NULL,
    period_start   DATE,
    period_end     DATE,
    figma_file_key VARCHAR(255),
    status         VARCHAR(255) NOT NULL,
    prepared_at    TIMESTAMP(6),
    confirmed_at   TIMESTAMP(6),
    closed_at      TIMESTAMP(6),
    created_by     BIGINT       NOT NULL,
    version        INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_sprint_sprint_key UNIQUE (sprint_key),
    CONSTRAINT uk_sprint_notion_page_id UNIQUE (notion_page_id),
    CONSTRAINT ck_sprint_status CHECK (status IN ('DRAFT', 'PREPARING', 'PREPARE_FAILED', 'REVIEW', 'IN_PROGRESS', 'CLOSED'))
);

-- 작업 큐: 셋업·자동 실행·리뷰 수집·증적 정리
CREATE TABLE job
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(255) NOT NULL,
    sprint_id        BIGINT REFERENCES sprint (id),
    status           VARCHAR(255) NOT NULL,
    payload          JSONB        NOT NULL DEFAULT '{}'::jsonb,
    attempt          INTEGER      NOT NULL DEFAULT 0,
    max_attempts     INTEGER      NOT NULL,
    run_after        TIMESTAMP(6) NOT NULL,
    locked_by        VARCHAR(255),
    locked_at        TIMESTAMP(6),
    heartbeat_at     TIMESTAMP(6),
    cancel_requested BOOLEAN      NOT NULL DEFAULT FALSE,
    last_error       TEXT,
    created_at       TIMESTAMP(6) NOT NULL,
    finished_at      TIMESTAMP(6),
    CONSTRAINT ck_job_type CHECK (type IN ('SETUP', 'AUTO_RUN', 'REVIEW_COLLECT', 'EVIDENCE_CLEANUP')),
    CONSTRAINT ck_job_status CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_job_attempt CHECK (attempt >= 0 AND max_attempts >= 1 AND attempt <= max_attempts)
);

-- 작업 소비 쿼리(status, type, run_after) 조회용
CREATE INDEX IF NOT EXISTS ix_job_status_type_run_after ON job (status, type, run_after);

-- 스프린트당 실행 중인 SETUP, AUTO_RUN 작업은 각각 1개
CREATE UNIQUE INDEX IF NOT EXISTS ux_job_active_per_sprint
    ON job (sprint_id, type)
    WHERE status IN ('QUEUED', 'RUNNING') AND type IN ('SETUP', 'AUTO_RUN');

-- 작업 단계: [QA 준비하기] 진행 표시
CREATE TABLE job_step
(
    job_id      BIGINT       NOT NULL REFERENCES job (id) ON DELETE CASCADE,
    seq         INTEGER      NOT NULL,
    name        VARCHAR(100) NOT NULL,
    status      VARCHAR(255) NOT NULL,
    message     TEXT,
    started_at  TIMESTAMP(6),
    finished_at TIMESTAMP(6),
    PRIMARY KEY (job_id, seq),
    CONSTRAINT ck_job_step_status CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED', 'SKIPPED'))
);

-- 기준점: 스프린트당 1개, 재준비 시 교체
CREATE TABLE baseline
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id            BIGINT       NOT NULL REFERENCES sprint (id),
    previous_baseline_id BIGINT REFERENCES baseline (id),
    created_at           TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_baseline_sprint_id UNIQUE (sprint_id)
);

-- 기준점의 저장소별 release 커밋과 AOS 버전
CREATE TABLE baseline_repo
(
    baseline_id          BIGINT       NOT NULL REFERENCES baseline (id) ON DELETE CASCADE,
    repo                 VARCHAR(255) NOT NULL,
    branch               VARCHAR(255) NOT NULL,
    commit_sha           CHAR(40)     NOT NULL,
    previous_commit_sha  CHAR(40),
    aos_version_code     INTEGER,
    aos_version_name     VARCHAR(100),
    version_code_warning BOOLEAN      NOT NULL DEFAULT FALSE,
    PRIMARY KEY (baseline_id, repo),
    CONSTRAINT ck_baseline_repo_repo CHECK (repo IN ('gravit-server', 'gravit-web', 'gravit-aos'))
);

-- 기능: Notion 기능 명세 DB 사본
CREATE TABLE feature
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id             VARCHAR(100) NOT NULL,
    name                  VARCHAR(255) NOT NULL,
    route                 VARCHAR(255),
    parts                 TEXT[]       NOT NULL DEFAULT '{}',
    notion_page_id        VARCHAR(64)  NOT NULL,
    spec_status           VARCHAR(255) NOT NULL,
    related_operation_ids TEXT[]       NOT NULL DEFAULT '{}',
    created_at            TIMESTAMP(6) NOT NULL,
    updated_at            TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_feature_screen_id UNIQUE (screen_id),
    CONSTRAINT uk_feature_notion_page_id UNIQUE (notion_page_id),
    CONSTRAINT ck_feature_parts CHECK (parts <@ ARRAY ['SERVER', 'WEB', 'APP']::TEXT[]),
    CONSTRAINT ck_feature_spec_status CHECK (spec_status IN ('DRAFT', 'NEEDS_CHECK', 'CONFIRMED'))
);

-- 스프린트 대상 기능: Notion 대상 기능 relation 사본
CREATE TABLE sprint_feature
(
    sprint_id  BIGINT NOT NULL REFERENCES sprint (id) ON DELETE CASCADE,
    feature_id BIGINT NOT NULL REFERENCES feature (id),
    PRIMARY KEY (sprint_id, feature_id)
);

-- 스냅샷: 준비 시점 수집 원본(보존 정리 대상 아님)
CREATE TABLE snapshot
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id    BIGINT       NOT NULL REFERENCES sprint (id),
    job_id       BIGINT REFERENCES job (id),
    source       VARCHAR(255) NOT NULL,
    source_ref   VARCHAR(512) NOT NULL,
    content_hash CHAR(64)     NOT NULL,
    storage_path VARCHAR(512) NOT NULL,
    captured_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_snapshot_source CHECK (source IN ('NOTION_SPRINT', 'NOTION_SPEC', 'FIGMA_FRAME', 'GITHUB_DIFF', 'OPENAPI'))
);

-- 스프린트별 스냅샷 조회용
CREATE INDEX IF NOT EXISTS ix_snapshot_sprint_id ON snapshot (sprint_id);

-- 체크 항목: 기능 아래 검수 항목
CREATE TABLE checklist_item
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id      BIGINT       NOT NULL REFERENCES sprint (id),
    feature_id     BIGINT       NOT NULL REFERENCES feature (id),
    title          TEXT         NOT NULL,
    expected       TEXT         NOT NULL,
    parts          TEXT[]       NOT NULL,
    classification VARCHAR(255) NOT NULL,
    criteria       JSONB,
    automation_gap BOOLEAN      NOT NULL DEFAULT FALSE,
    test_ref       VARCHAR(255),
    persona_key    VARCHAR(100),
    source_refs    JSONB        NOT NULL DEFAULT '[]'::jsonb,
    origin         VARCHAR(255) NOT NULL,
    review_state   VARCHAR(255) NOT NULL,
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    version        INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_checklist_item_parts CHECK (cardinality(parts) >= 1 AND parts <@ ARRAY ['SERVER', 'WEB', 'APP']::TEXT[]),
    CONSTRAINT ck_checklist_item_classification CHECK (classification IN ('AUTO', 'MANUAL')),
    CONSTRAINT ck_checklist_item_origin CHECK (origin IN ('LLM', 'HUMAN')),
    CONSTRAINT ck_checklist_item_review_state CHECK (review_state IN ('PROPOSED', 'CONFIRMED', 'REJECTED')),
    CONSTRAINT ck_checklist_item_auto_test_ref CHECK (classification <> 'AUTO' OR test_ref IS NOT NULL)
);

-- 체크리스트 화면 정렬 조회용
CREATE INDEX IF NOT EXISTS ix_checklist_item_sprint_feature_order ON checklist_item (sprint_id, feature_id, sort_order);

-- 자동 실행
CREATE TABLE auto_run
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id        BIGINT       NOT NULL REFERENCES sprint (id),
    baseline_id      BIGINT       NOT NULL REFERENCES baseline (id),
    job_id           BIGINT       NOT NULL REFERENCES job (id),
    status           VARCHAR(255) NOT NULL,
    fixture_manifest JSONB,
    counts           JSONB,
    failure_reason   TEXT,
    created_at       TIMESTAMP(6) NOT NULL,
    started_at       TIMESTAMP(6),
    finished_at      TIMESTAMP(6),
    CONSTRAINT ck_auto_run_status CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED'))
);

-- 스프린트별 실행 목록 조회용
CREATE INDEX IF NOT EXISTS ix_auto_run_sprint_id ON auto_run (sprint_id, id DESC);

-- 체크 셀: 체크 항목 × 파트, 4상태
CREATE TABLE check_cell
(
    item_id     BIGINT       NOT NULL REFERENCES checklist_item (id) ON DELETE CASCADE,
    part        VARCHAR(255) NOT NULL,
    state       VARCHAR(255) NOT NULL,
    source      VARCHAR(255) NOT NULL,
    auto_run_id BIGINT REFERENCES auto_run (id),
    updated_by  BIGINT,
    updated_at  TIMESTAMP(6),
    version     INTEGER      NOT NULL DEFAULT 0,
    PRIMARY KEY (item_id, part),
    CONSTRAINT ck_check_cell_part CHECK (part IN ('SERVER', 'WEB', 'APP')),
    CONSTRAINT ck_check_cell_state CHECK (state IN ('UNCHECKED', 'PASS', 'FAIL', 'NOT_APPLICABLE')),
    CONSTRAINT ck_check_cell_source CHECK (source IN ('MANUAL', 'AUTO')),
    CONSTRAINT ck_check_cell_auto_run CHECK (source <> 'AUTO' OR state = 'UNCHECKED' OR auto_run_id IS NOT NULL)
);

-- 체크 셀 변경 이력(감사용, 삭제하지 않음)
CREATE TABLE check_cell_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     BIGINT       NOT NULL,
    part        VARCHAR(255) NOT NULL,
    from_state  VARCHAR(255) NOT NULL,
    to_state    VARCHAR(255) NOT NULL,
    source      VARCHAR(255) NOT NULL,
    changed_by  BIGINT,
    auto_run_id BIGINT REFERENCES auto_run (id),
    changed_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_check_cell_history_cell FOREIGN KEY (item_id, part) REFERENCES check_cell (item_id, part) ON DELETE CASCADE,
    CONSTRAINT ck_check_cell_history_source CHECK (source IN ('MANUAL', 'AUTO'))
);

-- 셀별 이력 최신순 조회용
CREATE INDEX IF NOT EXISTS ix_check_cell_history_cell ON check_cell_history (item_id, part, changed_at DESC);

-- 자동 실행 케이스 결과
CREATE TABLE run_case_result
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        BIGINT       NOT NULL REFERENCES auto_run (id) ON DELETE CASCADE,
    item_id       BIGINT       NOT NULL REFERENCES checklist_item (id) ON DELETE CASCADE,
    test_ref      VARCHAR(255) NOT NULL,
    part          VARCHAR(255) NOT NULL,
    outcome       VARCHAR(255) NOT NULL,
    flaky         BOOLEAN      NOT NULL DEFAULT FALSE,
    attempts      INTEGER      NOT NULL DEFAULT 1,
    duration_ms   BIGINT,
    error_message TEXT,
    created_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_run_case_result_part CHECK (part IN ('SERVER', 'WEB', 'APP')),
    CONSTRAINT ck_run_case_result_outcome CHECK (outcome IN ('PASS', 'FAIL', 'ERROR', 'SKIPPED'))
);

-- 실행별 케이스 조회용
CREATE INDEX IF NOT EXISTS ix_run_case_result_run_id ON run_case_result (run_id);

-- 증적 파일 메타데이터
CREATE TABLE evidence
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT       NOT NULL REFERENCES auto_run (id),
    case_result_id BIGINT REFERENCES run_case_result (id),
    kind           VARCHAR(255) NOT NULL,
    storage_path   VARCHAR(512) NOT NULL,
    content_type   VARCHAR(100) NOT NULL,
    size_bytes     BIGINT       NOT NULL,
    sha256         CHAR(64)     NOT NULL,
    created_at     TIMESTAMP(6) NOT NULL,
    expires_at     TIMESTAMP(6) NOT NULL,
    deleted_at     TIMESTAMP(6),
    CONSTRAINT ck_evidence_kind CHECK (kind IN ('SCREENSHOT', 'TRACE', 'HTTP_LOG', 'CONSOLE_LOG')),
    CONSTRAINT ck_evidence_size CHECK (size_bytes >= 0)
);

-- 만료 정리 대상 조회용
CREATE INDEX IF NOT EXISTS ix_evidence_expires_at ON evidence (expires_at) WHERE deleted_at IS NULL;

-- 용량 합계 계산용
CREATE INDEX IF NOT EXISTS ix_evidence_alive_created_at ON evidence (created_at) WHERE deleted_at IS NULL;

-- 코드 검수 리포트(GitHub Checks 수집)
CREATE TABLE review_check
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id    BIGINT       NOT NULL REFERENCES sprint (id),
    repo         VARCHAR(255) NOT NULL,
    commit_sha   CHAR(40)     NOT NULL,
    check_name   VARCHAR(255) NOT NULL,
    status       VARCHAR(50)  NOT NULL,
    conclusion   VARCHAR(50),
    details_url  VARCHAR(1024),
    completed_at TIMESTAMP(6),
    collected_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_review_check UNIQUE (sprint_id, repo, commit_sha, check_name),
    CONSTRAINT ck_review_check_repo CHECK (repo IN ('gravit-server', 'gravit-web', 'gravit-aos'))
);

-- 페르소나 매니페스트: 세트별 마지막 적재 결과
CREATE TABLE persona_manifest
(
    persona_set VARCHAR(255) PRIMARY KEY,
    loaded_at   TIMESTAMP(6) NOT NULL,
    personas    JSONB        NOT NULL,
    CONSTRAINT ck_persona_manifest_set CHECK (persona_set IN ('auto', 'manual'))
);
