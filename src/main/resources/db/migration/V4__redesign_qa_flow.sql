-- V4__redesign_qa_flow.sql

-- 자동 실행 틀(D13)의 증적, 케이스 결과, 리뷰 수집, 페르소나 테이블을 지운다
DROP TABLE evidence;
DROP TABLE run_case_result;
DROP TABLE review_check;
DROP TABLE persona_manifest;

-- 체크 셀과 셀 이력이 자동 실행을 가리키지 않게 연결 컬럼을 지운다
ALTER TABLE check_cell
    DROP CONSTRAINT ck_check_cell_auto_run,
    DROP COLUMN auto_run_id;
ALTER TABLE check_cell_history
    DROP COLUMN auto_run_id;

-- 자동 실행 테이블을 지운다
DROP TABLE auto_run;

-- 기준점은 새 흐름에서 쓰지 않는다. 저장소 커밋은 sprint_connection에 남긴다
DROP TABLE baseline_repo;
DROP TABLE baseline;

-- 진행 중이던 스프린트의 체크 항목은 새 흐름에서 다시 만든다(셀, 셀 이력은 함께 지워진다)
DELETE FROM checklist_item
WHERE sprint_id IN (SELECT id FROM sprint WHERE status <> 'CLOSED');

-- 진행 중이던 스프린트를 새 흐름의 처음으로 되돌리고 상태 값을 새 흐름으로 바꾼다
ALTER TABLE sprint DROP CONSTRAINT ck_sprint_status;
UPDATE sprint SET status = 'DRAFT' WHERE status <> 'CLOSED';
ALTER TABLE sprint
    ADD CONSTRAINT ck_sprint_status CHECK (status IN ('DRAFT', 'SPEC_LOAD', 'CHECKLIST', 'DESIGN_REVIEW', 'AUTO_REVIEW', 'MANUAL_REVIEW', 'CLOSED'));

-- 응답에서 빠진 기간, 준비·확정 시각, 준비 실패 사유, 스프린트 경고를 지우고 Notion '변경 요약'을 둔다
ALTER TABLE sprint
    DROP COLUMN period_start,
    DROP COLUMN period_end,
    DROP COLUMN prepared_at,
    DROP COLUMN confirmed_at,
    DROP COLUMN prepare_failure_reason,
    DROP COLUMN warnings,
    ADD COLUMN change_summary TEXT;

-- 스냅샷이 지울 작업을 가리키지 않게 연결을 끊고, 새 흐름에서 만들지 않는 출처의 행을 지운다
UPDATE snapshot SET job_id = NULL;
DELETE FROM snapshot WHERE source IN ('FIGMA_FRAME', 'GITHUB_DIFF');
ALTER TABLE snapshot DROP CONSTRAINT ck_snapshot_source;
ALTER TABLE snapshot
    ADD CONSTRAINT ck_snapshot_source CHECK (source IN ('NOTION_SPRINT', 'NOTION_SPEC', 'FIGMA_NODES', 'OPENAPI'));

-- 작업 종류를 명세 로드(SPEC_LOAD), QA 준비(QA_PREPARE)로 바꾼다. 지운 종류의 작업은 단계와 함께 지운다
DELETE FROM job;
ALTER TABLE job DROP CONSTRAINT ck_job_type;
ALTER TABLE job
    ADD CONSTRAINT ck_job_type CHECK (type IN ('SPEC_LOAD', 'QA_PREPARE'));

-- 스프린트당 실행 중인 작업은 종류마다 1개
DROP INDEX ux_job_active_per_sprint;
CREATE UNIQUE INDEX IF NOT EXISTS ux_job_active_per_sprint
    ON job (sprint_id, type)
    WHERE status IN ('QUEUED', 'RUNNING');

-- 체크 항목에서 분류 기준, 테스트 카탈로그, 페르소나, 검토 상태를 지우고 근거 명세 행 번호를 둔다
ALTER TABLE checklist_item
    DROP CONSTRAINT ck_checklist_item_auto_test_ref,
    DROP CONSTRAINT ck_checklist_item_review_state,
    DROP COLUMN criteria,
    DROP COLUMN automation_gap,
    DROP COLUMN test_ref,
    DROP COLUMN persona_key,
    DROP COLUMN review_state,
    ADD COLUMN spec_row_ids TEXT[] NOT NULL DEFAULT '{}';

-- 1차 판정 사유와 사람 변경 이력의 사유
ALTER TABLE check_cell
    ADD COLUMN reason TEXT;
ALTER TABLE check_cell_history
    ADD COLUMN reason TEXT;

-- 스프린트 대상 기능: 기능 경고를 지우고 기준 명세(본문, 본문 표 행, 수정 이력)와 변경 여부를 둔다
ALTER TABLE sprint_feature
    DROP COLUMN warnings,
    ADD COLUMN changed       BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN spec_markdown TEXT    NOT NULL DEFAULT '',
    ADD COLUMN spec_rows     JSONB   NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN history_rows  JSONB   NOT NULL DEFAULT '[]'::jsonb;

-- 연결 상태: 마지막 준비 작업에서 Notion, Figma, 세 저장소를 읽었는지와 저장소 커밋
CREATE TABLE sprint_connection
(
    sprint_id  BIGINT       NOT NULL REFERENCES sprint (id) ON DELETE CASCADE,
    target     VARCHAR(255) NOT NULL,
    connected  BOOLEAN      NOT NULL,
    branch     VARCHAR(255),
    commit_sha CHAR(40),
    message    TEXT,
    checked_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (sprint_id, target),
    CONSTRAINT ck_sprint_connection_target CHECK (target IN ('NOTION', 'FIGMA', 'SERVER', 'WEB', 'APP'))
);

-- 준비 단계 진행: 화면에 보이는 5단계의 상태와 시도 횟수
CREATE TABLE sprint_step
(
    sprint_id   BIGINT       NOT NULL REFERENCES sprint (id) ON DELETE CASCADE,
    step_key    VARCHAR(255) NOT NULL,
    status      VARCHAR(255) NOT NULL,
    attempt     INTEGER      NOT NULL DEFAULT 0,
    message     TEXT,
    started_at  TIMESTAMP(6),
    finished_at TIMESTAMP(6),
    PRIMARY KEY (sprint_id, step_key),
    CONSTRAINT ck_sprint_step_key CHECK (step_key IN ('CONNECT', 'SPEC_COLLECT', 'CHECKLIST_GENERATE', 'DESIGN_REVIEW', 'AUTO_REVIEW')),
    CONSTRAINT ck_sprint_step_status CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED', 'WAITING'))
);

-- 준비 단위 진행: LLM을 쓰는 단계에서 화면(또는 화면 × 파트) 단위로 끝난 것을 기록해 다시 시작할 때 건너뛴다
CREATE TABLE prepare_unit
(
    sprint_id   BIGINT       NOT NULL REFERENCES sprint (id) ON DELETE CASCADE,
    step_key    VARCHAR(255) NOT NULL,
    unit_key    VARCHAR(255) NOT NULL,
    detail      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    finished_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (sprint_id, step_key, unit_key)
);

-- 수정 이력 반영 제안: 명세 1개의 이번 스프린트 이력 행을 본문에 반영하는 편집 목록과 바뀌기 전후 본문
CREATE TABLE spec_reflection
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id       BIGINT       NOT NULL REFERENCES sprint (id) ON DELETE CASCADE,
    feature_id      BIGINT       NOT NULL REFERENCES feature (id),
    history_rows    JSONB        NOT NULL DEFAULT '[]'::jsonb,
    operations      JSONB        NOT NULL DEFAULT '[]'::jsonb,
    base_blocks     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    before_markdown TEXT         NOT NULL,
    after_markdown  TEXT         NOT NULL,
    appliable       BOOLEAN      NOT NULL DEFAULT TRUE,
    state           VARCHAR(255) NOT NULL,
    message         TEXT,
    decided_by      BIGINT,
    decided_at      TIMESTAMP(6),
    version         INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_spec_reflection_state CHECK (state IN ('PENDING', 'APPROVED', 'REJECTED', 'APPLIED', 'FAILED'))
);

-- 스프린트별 반영 제안 조회용
CREATE INDEX IF NOT EXISTS ix_spec_reflection_sprint_id ON spec_reflection (sprint_id, feature_id);

-- 디자인 검수 항목: 화면 1개 × 플랫폼 1개 안의 화면 영역 단위
CREATE TABLE design_review_item
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sprint_id      BIGINT       NOT NULL REFERENCES sprint (id) ON DELETE CASCADE,
    feature_id     BIGINT       NOT NULL REFERENCES feature (id),
    platform       VARCHAR(255) NOT NULL,
    title          TEXT         NOT NULL,
    expected       TEXT         NOT NULL,
    spec_row_ids   TEXT[]       NOT NULL DEFAULT '{}',
    figma_node_ids TEXT[]       NOT NULL DEFAULT '{}',
    state          VARCHAR(255) NOT NULL,
    source         VARCHAR(255) NOT NULL,
    reason         TEXT,
    updated_by     BIGINT,
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    version        INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_design_review_item_platform CHECK (platform IN ('WEB', 'APP')),
    CONSTRAINT ck_design_review_item_state CHECK (state IN ('UNCHECKED', 'PASS', 'FAIL')),
    CONSTRAINT ck_design_review_item_source CHECK (source IN ('MANUAL', 'AUTO'))
);

-- 디자인 검수 화면 정렬 조회용
CREATE INDEX IF NOT EXISTS ix_design_review_item_sprint_feature_order ON design_review_item (sprint_id, feature_id, platform, sort_order);

-- 디자인 검수 항목 변경 이력(자동 판정, 사람 변경)
CREATE TABLE design_review_item_history
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT       NOT NULL REFERENCES design_review_item (id) ON DELETE CASCADE,
    from_state VARCHAR(255) NOT NULL,
    to_state   VARCHAR(255) NOT NULL,
    source     VARCHAR(255) NOT NULL,
    reason     TEXT,
    changed_by BIGINT,
    changed_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_design_review_item_history_source CHECK (source IN ('MANUAL', 'AUTO'))
);

-- 항목별 이력 최신순 조회용
CREATE INDEX IF NOT EXISTS ix_design_review_item_history_item ON design_review_item_history (item_id, changed_at DESC);
